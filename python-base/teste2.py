turno = input('Digite m para manhã, t para tarde, ou n para noite: ')
if turno =='m':
         print('Bom dia!')
else:
         if turno =='t':
                  print('Boa tarde!')
         else:
                  if turno =='n':
                           print('Boa noite!')
                  else:
                           print('Letra inválida')